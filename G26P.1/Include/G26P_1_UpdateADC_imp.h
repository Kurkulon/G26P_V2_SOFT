u16 netResist = 0;
u16 fltResist = 0;

//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

u16 GetNetAdr()
{
	return 1 + netResist/1024;
}

//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

void UpdateADC()
{
	static byte i = 0;
	static CTM32 tm;

	static DSCSPI dsc;
	static u16 buf;

	switch (i)
	{
		case 0:

			if (tm.Check(MS2CTM(1)) && adcEnable)
			{
				dsc.baud = 50;
				dsc.mode = CPOL;//(CPOL|CPHA|LSBF);
				dsc.csnum = 1;
				dsc.rdata = &buf;
				dsc.rlen = sizeof(buf);

				spi1.AddRequest(&dsc);

				i++;
			};

			break;

		case 1:

			if (dsc.ready)
			{
				netResist = (ReverseWord(buf) * 10296 + 2048) / 4096; 

				i = 0;
			};

			break;
	};
}

