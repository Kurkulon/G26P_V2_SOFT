//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

void UpdateHardware()
{
	static byte i = 0;

	#define CALL(p) case (__LINE__-S): p; break;

	enum C { S = (__LINE__+3) };
	switch(i++)
	{
		CALL( UpdateADC()	);
		CALL( spi1.Update()	);
	};

	i = (i > (__LINE__-S-3)) ? 0 : i;

	#undef CALL

	*pWDOG_STAT = 0; //Reset WDT
}

