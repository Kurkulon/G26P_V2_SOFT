static u16 SPI1_CS_MASK[] = { PG11, PG12 };

static S_SPIM	spi1(1, HW::PIOG, SPI1_CS_MASK, ArraySize(SPI1_CS_MASK), SCLK);

#define adcEnable 1

//++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

void InitHardware()
{
	LowLevelInit();

	spi1.Connect(1000000);

	CTM32 tm;

	tm.Reset();

	while(!tm.Check(MS2CTM(10))) UpdateHardware();
}

